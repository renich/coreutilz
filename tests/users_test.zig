test "users with file argument" {
    const allocator = testing.allocator;
    var ctx = try TestContext.init(allocator);
    defer ctx.deinit();

    const binary_path = try getBinaryPath(allocator, "users");
    defer allocator.free(binary_path);

    // Create an empty file to test if it accepts it
    try ctx.writeFile("mock_utmp", "");
    const tmp_path = try ctx.tmpPath("mock_utmp");
    defer allocator.free(tmp_path);

    var result = try ctx.runCommand(&[_][]const u8{ binary_path, tmp_path }, null);
    defer result.deinit();

    // It should at least run without crashing, even if file is empty or invalid
    // Depending on implementation, it might exit with 0 or error.
    // GNU users returns 0 for empty file usually.
    try testing.expectEqual(@as(u8, 0), result.exit_code);
}
